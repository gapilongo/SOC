#!/usr/bin/env bash
# Configure a GitHub environment (dev or uat) to deploy to this PC over
# Tailscale (docs/self-hosting-pc.md, step 5). Run it as your normal user,
# after setup-host.sh and 'gh auth login', once per environment. It is safe to
# run again:
#
#   bash deploy/pc/configure-github.sh --env dev --admin-email you@example.com
#   bash deploy/pc/configure-github.sh --env uat --admin-email you@example.com
#   bash deploy/pc/configure-github.sh --env dev --dry-run   # names only, changes nothing
#
# What it does:
#   * creates or updates the environment: dev deploys only from the branch
#     main, uat only from tags v*.*.* and waits for your approval (unless
#     --no-reviewer);
#   * sets the variables DEPLOY_HOST (this PC's tailnet IPv4), DEPLOY_USER,
#     DEPLOY_PORT, APP_DOMAIN (soc-<env>.<tailnet>.ts.net),
#     BOOTSTRAP_ADMIN_EMAIL, LLM_PROVIDER, INGRESS=funnel and
#     DEPLOY_VIA_TAILSCALE=true;
#   * sets the secrets DEPLOY_SSH_KEY and DEPLOY_SSH_KNOWN_HOSTS from the files
#     setup-host.sh wrote in ~/.config/lg-sotf; TS_OAUTH_CLIENT_ID,
#     TS_OAUTH_SECRET and TS_AUTHKEY from hidden prompts (or files), asked only
#     when not set yet; optionally ANTHROPIC_API_KEY; and the eight
#     application secrets generated by scripts/generate_secrets.py;
#   * never replaces application secrets that already exist. The database
#     keeps the passwords it was created with on the first deploy, so changing
#     them in GitHub afterwards makes every deploy fail (and roll back).
#     --rotate-app-secrets replaces all eight: use it only before the first
#     deploy, or after deleting the environment's database;
#   * saves a newly generated first-admin password in
#     ~/.config/lg-sotf/<env>-admin-password (0600) and prints only that path.
#
# Secret values go to 'gh secret set' on its standard input, never on a
# command line, and are never printed.
#
# Options:
#   --env dev|uat                 environment to configure (required)
#   --tailnet NAME.ts.net         your tailnet DNS name (default: the one
#                                 setup-host.sh saved in ~/.config/lg-sotf/tailnet)
#   --admin-email EMAIL           first admin account (required on the first run)
#   --repo OWNER/NAME             default: the GitHub repository of this clone
#   --llm-provider NAME           fake, anthropic, openai or gemini (default:
#                                 anthropic when ANTHROPIC_API_KEY is set, else fake)
#   --ts-oauth-client-id-file F   read TS_OAUTH_CLIENT_ID from file F
#   --ts-oauth-secret-file F      read TS_OAUTH_SECRET from file F
#   --ts-authkey-file F           read TS_AUTHKEY from file F
#   --update-tailscale-secrets    ask again for Tailscale secrets that are already set
#   --anthropic-key-file F        set ANTHROPIC_API_KEY from file F
#   --ask-anthropic-key           set ANTHROPIC_API_KEY from a hidden prompt
#   --rotate-app-secrets          regenerate the eight application secrets (see above)
#   --yes                         no confirmation prompt for --rotate-app-secrets
#   --no-reviewer                 uat: deploy without waiting for a reviewer
#   --auto-deploy                 set the repository variable AUTO_DEPLOY_DEV or
#                                 AUTO_DEPLOY_UAT to true (deploy on every build/tag)
#   --no-auto-deploy              set it to false
#   --config-dir DIR              default ~/.config/lg-sotf
#   --dry-run                     print the names that would be set; change nothing
#   -h, --help                    show this text

set -euo pipefail
umask 077

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_DIR="$(cd "$SCRIPT_DIR/../.." && pwd)"
GENERATOR="$REPO_DIR/scripts/generate_secrets.py"

APP_SECRETS=(
  POSTGRES_SUPERUSER_PASSWORD LGSOTF_OWNER_PASSWORD LGSOTF_APP_PASSWORD
  LG_SOTF_AUTH__JWT_SECRET LG_SOTF_SECURITY__ENCRYPTION_KEYS LG_SOTF_SECURITY__INDICATOR_HMAC_KEY
  LG_SOTF_API__METRICS_TOKEN LG_SOTF_AUTH__BOOTSTRAP_ADMIN_PASSWORD
)
TS_SECRETS=(TS_OAUTH_CLIENT_ID TS_OAUTH_SECRET TS_AUTHKEY)
VARIABLES=(DEPLOY_HOST DEPLOY_USER DEPLOY_PORT APP_DOMAIN BOOTSTRAP_ADMIN_EMAIL LLM_PROVIDER INGRESS DEPLOY_VIA_TAILSCALE)
EMAIL_RE='^[^@[:space:]]+@[^@[:space:]]+\.[^@[:space:]]+$'

ENV_NAME=""
TAILNET=""
ADMIN_EMAIL=""
REPO=""
LLM_PROVIDER=""
CONFIG_DIR="${HOME:?}/.config/lg-sotf"
ANTHROPIC_FILE=""
ASK_ANTHROPIC=0
UPDATE_TS=0
ROTATE=0
YES=0
REVIEWER=1
AUTO_DEPLOY=""
DRY_RUN=0
declare -A TS_FILE=()

log() { printf '%s\n' "$*"; }
warn() { printf 'WARNING: %s\n' "$*" >&2; }
die() { printf 'ERROR: %s\n' "$*" >&2; exit 2; }
usage() { awk 'NR == 1 { next } /^#/ { sub(/^# ?/, ""); print; next } { exit }' "$0"; }
need_value() { [ "$2" -ge 2 ] || { printf 'ERROR: %s needs a value\n' "$1" >&2; exit 64; }; }

while [ $# -gt 0 ]; do
  case "$1" in
    --env) need_value "$1" $#; ENV_NAME="$2"; shift 2 ;;
    --tailnet) need_value "$1" $#; TAILNET="$2"; shift 2 ;;
    --admin-email) need_value "$1" $#; ADMIN_EMAIL="$2"; shift 2 ;;
    --repo) need_value "$1" $#; REPO="$2"; shift 2 ;;
    --llm-provider) need_value "$1" $#; LLM_PROVIDER="$2"; shift 2 ;;
    --ts-oauth-client-id-file) need_value "$1" $#; TS_FILE[TS_OAUTH_CLIENT_ID]="$2"; shift 2 ;;
    --ts-oauth-secret-file) need_value "$1" $#; TS_FILE[TS_OAUTH_SECRET]="$2"; shift 2 ;;
    --ts-authkey-file) need_value "$1" $#; TS_FILE[TS_AUTHKEY]="$2"; shift 2 ;;
    --update-tailscale-secrets) UPDATE_TS=1; shift ;;
    --anthropic-key-file) need_value "$1" $#; ANTHROPIC_FILE="$2"; shift 2 ;;
    --ask-anthropic-key) ASK_ANTHROPIC=1; shift ;;
    --rotate-app-secrets) ROTATE=1; shift ;;
    --yes) YES=1; shift ;;
    --no-reviewer) REVIEWER=0; shift ;;
    --auto-deploy) AUTO_DEPLOY=true; shift ;;
    --no-auto-deploy) AUTO_DEPLOY=false; shift ;;
    --config-dir) need_value "$1" $#; CONFIG_DIR="$2"; shift 2 ;;
    --dry-run) DRY_RUN=1; shift ;;
    -h|--help) usage; exit 0 ;;
    *) printf 'ERROR: unknown argument: %s (see --help)\n' "$1" >&2; exit 64 ;;
  esac
done

# ------------------------------------------------------------------ arguments
[[ "$ENV_NAME" =~ ^(dev|uat)$ ]] || die "--env must be dev or uat"
ENV_UPPER="$(printf '%s' "$ENV_NAME" | tr '[:lower:]' '[:upper:]')"
if [ -z "$TAILNET" ] && [ -f "$CONFIG_DIR/tailnet" ]; then TAILNET="$(sed -n 1p "$CONFIG_DIR/tailnet")"; fi
TAILNET="$(printf '%s' "$TAILNET" | tr '[:upper:]' '[:lower:]' | sed -e 's#^https\{0,1\}://##' -e 's#^\.##' -e 's#[./]*$##')"
[[ "$TAILNET" =~ ^[a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?\.ts\.net$ ]] \
  || die "give your tailnet DNS name with --tailnet (e.g. tail1234.ts.net; admin console > DNS)"
APP_DOMAIN="soc-$ENV_NAME.$TAILNET"
[ -z "$ADMIN_EMAIL" ] || [[ "$ADMIN_EMAIL" =~ $EMAIL_RE ]] || die "--admin-email is not an email address"
[ -z "$REPO" ] || [[ "$REPO" =~ ^[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+$ ]] || die "--repo must be OWNER/NAME"
[ -z "$LLM_PROVIDER" ] || [[ "$LLM_PROVIDER" =~ ^(anthropic|openai|gemini|fake)$ ]] \
  || die "--llm-provider must be anthropic, openai, gemini or fake"
for name in "${!TS_FILE[@]}"; do
  [ -r "${TS_FILE[$name]}" ] || die "cannot read the file given for $name"
done
[ -z "$ANTHROPIC_FILE" ] || [ -r "$ANTHROPIC_FILE" ] || die "cannot read --anthropic-key-file"
[ -f "$GENERATOR" ] || die "scripts/generate_secrets.py not found next to this script"
command -v python3 >/dev/null || die "python3 is required"

# ------------------------------------------------------------------ files from setup-host.sh
KEY_FILE="$CONFIG_DIR/deploy_ed25519"
KNOWN_HOSTS_FILE="$CONFIG_DIR/known_hosts"
MISSING_LOCAL=()
DEPLOY_HOST=""
if [ -f "$CONFIG_DIR/deploy_host" ]; then DEPLOY_HOST="$(sed -n 1p "$CONFIG_DIR/deploy_host")"; fi
[[ "$DEPLOY_HOST" =~ ^100\.[0-9]{1,3}\.[0-9]{1,3}\.[0-9]{1,3}$ ]] || MISSING_LOCAL+=("$CONFIG_DIR/deploy_host")
if [ ! -r "$KEY_FILE" ] || ! grep -q -- '-----BEGIN OPENSSH PRIVATE KEY-----' "$KEY_FILE"; then
  MISSING_LOCAL+=("$KEY_FILE")
fi
if [ ! -s "$KNOWN_HOSTS_FILE" ] || [ "$(awk '{ print $1; exit }' "$KNOWN_HOSTS_FILE")" != "$DEPLOY_HOST" ]; then
  MISSING_LOCAL+=("$KNOWN_HOSTS_FILE")
fi
if [ "${#MISSING_LOCAL[@]}" -gt 0 ] && [ "$DRY_RUN" -eq 0 ]; then
  die "missing or stale: ${MISSING_LOCAL[*]}; run  sudo bash deploy/pc/setup-host.sh  first"
fi
if [ -f "$KEY_FILE" ]; then
  case "$(stat -c %a "$KEY_FILE")" in ?00) ;; *) warn "$KEY_FILE is readable by other users: chmod 600 it" ;; esac
fi

# ------------------------------------------------------------------ GitHub
command -v gh >/dev/null || die "the GitHub CLI (gh) is not installed (docs/self-hosting-pc.md, step 5)"
GH_OK=1
gh auth status >/dev/null 2>&1 || GH_OK=0
if [ "$GH_OK" -eq 0 ] && [ "$DRY_RUN" -eq 0 ]; then die "sign in to GitHub first: gh auth login"; fi

gh_get() { gh api -H 'Accept: application/vnd.github+json' "$1" 2>/dev/null; }

json_field() {  # json_field KEY... < json: the value at that path, '' when absent
  python3 -c '
import json, sys
try:
    v = json.load(sys.stdin)
    for k in sys.argv[1:]:
        v = v[k]
except (ValueError, KeyError, TypeError):
    v = ""
print(str(v).lower() if isinstance(v, bool) else ("" if v is None else v))
' "$@"
}

json_rows() {  # json_rows LIST_KEY FIELD... < json: one tab-separated row per item
  python3 -c '
import json, sys
try:
    items = json.load(sys.stdin).get(sys.argv[1]) or []
except (ValueError, AttributeError):
    items = []
defaults = {"type": "branch"}
for item in items:
    print("\t".join(str(item.get(f, defaults.get(f, ""))) for f in sys.argv[2:]))
' "$@"
}

if [ "$GH_OK" -eq 1 ] && [ -z "$REPO" ]; then
  REPO="$( { (cd "$REPO_DIR" && gh repo view --json nameWithOwner) 2>/dev/null || true; } | json_field nameWithOwner)"
  [[ "$REPO" =~ ^[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+$ ]] || die "cannot tell the GitHub repository of this clone; pass --repo OWNER/NAME"
fi

ENV_EXISTS=0
declare -A HAVE_SECRET=()
declare -A HAVE_VAR=()
if [ "$GH_OK" -eq 1 ]; then
  body="$(gh_get "repos/$REPO")" || die "cannot read repository $REPO (gh auth status; is --repo right?)"
  [ "$(json_field permissions admin <<<"$body")" = "true" ] \
    || die "your GitHub account needs admin rights on $REPO to manage environments"
  if body="$(gh_get "repos/$REPO/environments/$ENV_NAME")"; then ENV_EXISTS=1; fi
  if [ "$ENV_EXISTS" -eq 1 ]; then
    body="$(gh_get "repos/$REPO/environments/$ENV_NAME/secrets?per_page=100")" \
      || die "cannot list the secrets of environment $ENV_NAME"
    while IFS= read -r name; do
      [ -z "$name" ] || HAVE_SECRET[$name]=1
    done < <(json_rows secrets name <<<"$body")
    body="$(gh_get "repos/$REPO/environments/$ENV_NAME/variables?per_page=30")" \
      || die "cannot list the variables of environment $ENV_NAME"
    while IFS=$'\t' read -r name value; do
      [ -z "$name" ] || HAVE_VAR[$name]="$value"
    done < <(json_rows variables name value <<<"$body")
  fi
fi

# ------------------------------------------------------------------ plan
if [ -z "$ADMIN_EMAIL" ]; then ADMIN_EMAIL="${HAVE_VAR[BOOTSTRAP_ADMIN_EMAIL]:-}"; fi
if [ -z "$ADMIN_EMAIL" ] && [ "$DRY_RUN" -eq 0 ]; then die "--admin-email is required the first time"; fi

declare -A TS_SOURCE=()
for name in "${TS_SECRETS[@]}"; do
  if [ -n "${TS_FILE[$name]:-}" ]; then
    TS_SOURCE[$name]="file"
  elif [ -z "${HAVE_SECRET[$name]:-}" ] || [ "$UPDATE_TS" -eq 1 ]; then
    TS_SOURCE[$name]="prompt"
  else
    TS_SOURCE[$name]="keep"
  fi
done

ANTHROPIC_SOURCE="none"
if [ -n "$ANTHROPIC_FILE" ]; then ANTHROPIC_SOURCE="file"; elif [ "$ASK_ANTHROPIC" -eq 1 ]; then ANTHROPIC_SOURCE="prompt"; fi
if [ -z "$LLM_PROVIDER" ]; then
  if [ "$ANTHROPIC_SOURCE" != "none" ] || [ -n "${HAVE_SECRET[ANTHROPIC_API_KEY]:-}" ]; then
    LLM_PROVIDER="anthropic"
  else
    LLM_PROVIDER="fake"
  fi
fi

GENERATE=()
KEEP=()
EXISTING_APP=0
for name in "${APP_SECRETS[@]}"; do
  [ -z "${HAVE_SECRET[$name]:-}" ] || EXISTING_APP=$((EXISTING_APP + 1))
  if [ "$ROTATE" -eq 1 ] || [ -z "${HAVE_SECRET[$name]:-}" ]; then GENERATE+=("$name"); else KEEP+=("$name"); fi
done

case "$ENV_NAME" in
  dev) POLICY_TYPE="branch"; POLICY_NAME="main" ;;
  uat) POLICY_TYPE="tag"; POLICY_NAME="v*.*.*" ;;
esac
[ "$ENV_NAME" = "uat" ] || REVIEWER=0

if [ "$DRY_RUN" -eq 1 ]; then
  ts_plan=""
  for name in "${TS_SECRETS[@]}"; do ts_plan="$ts_plan $name(${TS_SOURCE[$name]})"; done
  log "Dry run: nothing is changed; secret values are never shown."
  if [ "$GH_OK" -eq 0 ]; then log "  (not signed in to GitHub: 'gh auth login' first; existing settings are not known)"; fi
  if [ "${#MISSING_LOCAL[@]}" -gt 0 ]; then log "  missing (run setup-host.sh): ${MISSING_LOCAL[*]}"; fi
  if [ -n "$REPO" ]; then log "repository            $REPO"; else log "repository            (the repository of this clone)"; fi
  if [ "$ENV_EXISTS" -eq 1 ]; then log "environment           $ENV_NAME (update)"; else log "environment           $ENV_NAME (create)"; fi
  log "deployments from      $POLICY_TYPE $POLICY_NAME"
  if [ "$REVIEWER" -eq 1 ]; then log "required reviewer     you"; fi
  log "public URL            https://$APP_DOMAIN"
  log "variables             ${VARIABLES[*]}"
  log "secrets               DEPLOY_SSH_KEY DEPLOY_SSH_KNOWN_HOSTS"
  log "Tailscale secrets    $ts_plan"
  log "generate              ${GENERATE[*]:-(none)}"
  log "keep                  ${KEEP[*]:-(none)}"
  if [ "$ANTHROPIC_SOURCE" != "none" ]; then log "also                  ANTHROPIC_API_KEY ($ANTHROPIC_SOURCE)"; fi
  if [ -n "$AUTO_DEPLOY" ]; then log "repository variable   AUTO_DEPLOY_$ENV_UPPER"; fi
  exit 0
fi

# ------------------------------------------------------------------ collect secret input first
REPLY_SECRET=""
read_secret_file() {  # $1 file: first line, surrounding whitespace removed
  local value=""
  IFS= read -r value < "$1" || true
  value="${value%$'\r'}"
  value="${value#"${value%%[![:space:]]*}"}"
  value="${value%"${value##*[![:space:]]}"}"
  case "$(stat -c %a "$1")" in ?00) ;; *) warn "$1 is readable by other users: chmod 600 it, or delete it" ;; esac
  REPLY_SECRET="$value"
}
ask_secret() {  # $1 name, $2 prompt
  local value=""
  [ -t 0 ] || die "$1 is not set in environment $ENV_NAME: run this in a terminal to be asked for it, or pass its file option"
  IFS= read -rs -p "$2 (input hidden): " value
  printf '\n' >&2
  REPLY_SECRET="$value"
}
check_secret() {  # $1 name, $2 value; never prints the value
  case "$1" in
    TS_OAUTH_CLIENT_ID)
      if ! [[ "$2" =~ ^[A-Za-z0-9_-]{4,}$ ]] || [[ "$2" == tskey-* ]]; then
        die "TS_OAUTH_CLIENT_ID must be the OAuth client's ID (letters and digits), not its secret"
      fi ;;
    TS_OAUTH_SECRET)
      [[ "$2" =~ ^tskey-client-[[:graph:]]+$ ]] || die "TS_OAUTH_SECRET must start with tskey-client-" ;;
    TS_AUTHKEY)
      [[ "$2" =~ ^tskey-auth-[[:graph:]]+$ ]] || die "TS_AUTHKEY must be an auth key starting with tskey-auth-" ;;
    ANTHROPIC_API_KEY)
      [[ "$2" =~ ^sk-ant-[[:graph:]]+$ ]] || die "ANTHROPIC_API_KEY must start with sk-ant-" ;;
  esac
}

declare -A NEW_SECRET=()
for name in "${TS_SECRETS[@]}"; do
  case "${TS_SOURCE[$name]}" in
    file) read_secret_file "${TS_FILE[$name]}" ;;
    prompt)
      case "$name" in
        TS_OAUTH_CLIENT_ID) ask_secret "$name" "Tailscale OAuth client ID" ;;
        TS_OAUTH_SECRET) ask_secret "$name" "Tailscale OAuth client secret (tskey-client-...)" ;;
        TS_AUTHKEY) ask_secret "$name" "Tailscale auth key for tag:soc (tskey-auth-...)" ;;
      esac ;;
    keep) continue ;;
  esac
  check_secret "$name" "$REPLY_SECRET"
  NEW_SECRET[$name]="$REPLY_SECRET"
done
case "$ANTHROPIC_SOURCE" in
  file) read_secret_file "$ANTHROPIC_FILE" ;;
  prompt) ask_secret ANTHROPIC_API_KEY "Anthropic API key (sk-ant-...)" ;;
esac
if [ "$ANTHROPIC_SOURCE" != "none" ]; then
  check_secret ANTHROPIC_API_KEY "$REPLY_SECRET"
  NEW_SECRET[ANTHROPIC_API_KEY]="$REPLY_SECRET"
fi
REPLY_SECRET=""

if [ "$ROTATE" -eq 1 ] && [ "$EXISTING_APP" -gt 0 ]; then
  cat >&2 <<EOF
WARNING: --rotate-app-secrets replaces all eight application secrets of '$ENV_NAME'.
  * The database keeps the passwords it was created with: once '$ENV_NAME' has been
    deployed, new database passwords make every deploy fail until the database is
    deleted (all its data) or the old passwords are put back.
  * A new encryption key makes stored credentials unreadable; a new JWT secret signs
    everyone out. The first-admin password only matters before the first deploy.
EOF
  if [ "$YES" -eq 0 ]; then
    [ -t 0 ] || die "--rotate-app-secrets needs --yes when not run in a terminal"
    read -r -p "Type the environment name ($ENV_NAME) to continue: " answer
    [ "$answer" = "$ENV_NAME" ] || die "aborted; nothing was changed"
  fi
fi

declare -A GEN=()
if [ "${#GENERATE[@]}" -gt 0 ]; then
  generated="$(python3 "$GENERATOR")" || die "scripts/generate_secrets.py failed"
  while IFS= read -r line; do
    [[ "$line" =~ ^[A-Z][A-Z0-9_]*= ]] || continue
    GEN["${line%%=*}"]="${line#*=}"
  done <<<"$generated"
  generated=""
  for name in "${APP_SECRETS[@]}"; do
    [ -n "${GEN[$name]:-}" ] || die "scripts/generate_secrets.py did not produce $name"
  done
fi

# ------------------------------------------------------------------ apply
SET_SECRETS=()
set_secret() {  # $1 name; the value arrives on stdin
  gh secret set "$1" --env "$ENV_NAME" --repo "$REPO" >/dev/null || die "could not set secret $1"
  SET_SECRETS+=("$1")
}
set_variable() {  # $1 name, $2 value (not secret)
  gh variable set "$1" --env "$ENV_NAME" --repo "$REPO" --body "$2" >/dev/null || die "could not set variable $1"
}

reviewers="[]"
if [ "$REVIEWER" -eq 1 ]; then
  reviewer_id="$( { gh_get user || true; } | json_field id)"
  [[ "$reviewer_id" =~ ^[0-9]+$ ]] || die "cannot read your GitHub user id (gh api user)"
  reviewers="[{\"type\":\"User\",\"id\":$reviewer_id}]"
fi
printf '{"wait_timer":0,"prevent_self_review":false,"reviewers":%s,"deployment_branch_policy":{"protected_branches":false,"custom_branch_policies":true}}' \
  "$reviewers" | gh api --method PUT "repos/$REPO/environments/$ENV_NAME" --input - >/dev/null \
  || die "could not create or update environment $ENV_NAME"
if [ "$ENV_EXISTS" -eq 1 ]; then log "environment $ENV_NAME updated"; else log "environment $ENV_NAME created"; fi

policies="$(gh_get "repos/$REPO/environments/$ENV_NAME/deployment-branch-policies?per_page=100")" \
  || die "cannot list the deployment branch policies of $ENV_NAME"
found=0
while IFS=$'\t' read -r id type name; do
  [ -n "$id" ] || continue
  if [ "$type" = "$POLICY_TYPE" ] && [ "$name" = "$POLICY_NAME" ]; then
    found=1
    continue
  fi
  gh api --method DELETE "repos/$REPO/environments/$ENV_NAME/deployment-branch-policies/$id" >/dev/null \
    || die "could not remove the deployment $type policy '$name'"
  log "removed deployment $type policy '$name'"
done < <(json_rows branch_policies id type name <<<"$policies")
if [ "$found" -eq 0 ]; then
  printf '{"name":"%s","type":"%s"}' "$POLICY_NAME" "$POLICY_TYPE" \
    | gh api --method POST "repos/$REPO/environments/$ENV_NAME/deployment-branch-policies" --input - >/dev/null \
    || die "could not add the deployment $POLICY_TYPE policy '$POLICY_NAME'"
fi
log "deployments to $ENV_NAME only from $POLICY_TYPE $POLICY_NAME"

set_variable DEPLOY_HOST "$DEPLOY_HOST"
set_variable DEPLOY_USER deploy
set_variable DEPLOY_PORT 22
set_variable APP_DOMAIN "$APP_DOMAIN"
set_variable BOOTSTRAP_ADMIN_EMAIL "$ADMIN_EMAIL"
set_variable LLM_PROVIDER "$LLM_PROVIDER"
set_variable INGRESS funnel
set_variable DEPLOY_VIA_TAILSCALE true
log "variables: DEPLOY_HOST=$DEPLOY_HOST DEPLOY_USER=deploy DEPLOY_PORT=22 APP_DOMAIN=$APP_DOMAIN"
log "           BOOTSTRAP_ADMIN_EMAIL=$ADMIN_EMAIL LLM_PROVIDER=$LLM_PROVIDER INGRESS=funnel DEPLOY_VIA_TAILSCALE=true"

set_secret DEPLOY_SSH_KEY < "$KEY_FILE"
set_secret DEPLOY_SSH_KNOWN_HOSTS < "$KNOWN_HOSTS_FILE"
for name in "${TS_SECRETS[@]}" ANTHROPIC_API_KEY; do
  [ -n "${NEW_SECRET[$name]:-}" ] || continue
  set_secret "$name" < <(printf '%s' "${NEW_SECRET[$name]}")
  NEW_SECRET[$name]=""
done

ADMIN_PASSWORD_FILE=""
if [ "${#GENERATE[@]}" -gt 0 ]; then
  if [ -n "${GEN[LG_SOTF_AUTH__BOOTSTRAP_ADMIN_PASSWORD]:-}" ] \
     && [[ " ${GENERATE[*]} " == *" LG_SOTF_AUTH__BOOTSTRAP_ADMIN_PASSWORD "* ]]; then
    # Saved before GitHub gets it: GitHub secrets cannot be read back.
    ADMIN_PASSWORD_FILE="$CONFIG_DIR/$ENV_NAME-admin-password"
    mkdir -p "$CONFIG_DIR"
    tmp="$(mktemp "$ADMIN_PASSWORD_FILE.XXXXXX")"
    printf '%s\n' "${GEN[LG_SOTF_AUTH__BOOTSTRAP_ADMIN_PASSWORD]}" > "$tmp"
    chmod 0600 "$tmp"
    mv -f "$tmp" "$ADMIN_PASSWORD_FILE"
  fi
  for name in "${GENERATE[@]}"; do
    set_secret "$name" < <(printf '%s' "${GEN[$name]}")
    GEN[$name]=""
  done
fi

if [ -n "$AUTO_DEPLOY" ]; then
  gh variable set "AUTO_DEPLOY_$ENV_UPPER" --repo "$REPO" --body "$AUTO_DEPLOY" >/dev/null \
    || die "could not set the repository variable AUTO_DEPLOY_$ENV_UPPER"
  log "repository variable AUTO_DEPLOY_$ENV_UPPER=$AUTO_DEPLOY"
fi

# ------------------------------------------------------------------ repository settings (read only)
perms="$( { gh_get "repos/$REPO/actions/permissions/workflow" || true; } | json_field default_workflow_permissions)"
case "$perms" in
  read) ;;
  write) warn "workflows get a read/write GITHUB_TOKEN by default: Settings > Actions > General > Workflow permissions > Read repository contents and packages permissions" ;;
