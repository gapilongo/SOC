#!/usr/bin/env python3
"""Generate fresh LG-SOTF secrets as ``KEY=value`` lines (standard library only).

    python scripts/generate_secrets.py                 # print to stdout
    python scripts/generate_secrets.py --append .env   # append keys missing from .env
    python scripts/generate_secrets.py --format k8s    # kubectl create secret ... commands

Values are random and never logged. Output includes the application secrets
(JWT, Fernet encryption key, indicator HMAC key, metrics token), the database
passwords used by docker/docker-compose.prod.yml, and a bootstrap admin
password. Existing keys in an ``--append`` target are left untouched, so
re-running never rotates a secret by accident (rotation is a deliberate
procedure; see docs/operations.md).

``--format k8s`` prints shell commands for the Secrets the Helm chart expects,
split the same way the chart mounts them:

* ``<name>``: runtime Secret (envFrom in api, worker, scheduler, migrate):
  application keys, plus the connection URLs and LLM keys copied from this
  process's environment when set (otherwise listed as keys still to add).
* ``<name>-owner``: schema-owner DSN, only when LG_SOTF_DATABASE__MIGRATION_URL
  is set (migrate job and scheduler only).
* ``<name>-bootstrap``: first admin email and password (migrate job only),
  when an email is given with ``--admin-email`` or the environment.

Values are fed to ``kubectl --from-env-file=/dev/stdin`` through a quoted
here-document, so piping the output to ``sh`` keeps them out of shell history
and the process list. Database passwords for the compose override are never
included.
"""

from __future__ import annotations

import argparse
import base64
import os
import secrets
import shlex
import sys
from pathlib import Path
from typing import Dict, List, Mapping


def fernet_key() -> str:
    """A Fernet key: urlsafe base64 of 32 random bytes (same as ``Fernet.generate_key()``)."""
    return base64.urlsafe_b64encode(os.urandom(32)).decode("ascii")


def token(nbytes: int = 48) -> str:
    return secrets.token_urlsafe(nbytes)


def password() -> str:
    # URL-safe alphabet so the value can be embedded in a database URL unescaped.
    return secrets.token_urlsafe(24)


def generate() -> Dict[str, str]:
    return {
        "LG_SOTF_AUTH__JWT_SECRET": token(48),
        "LG_SOTF_SECURITY__ENCRYPTION_KEYS": fernet_key(),
        "LG_SOTF_SECURITY__INDICATOR_HMAC_KEY": token(48),
        "LG_SOTF_API__METRICS_TOKEN": token(32),
        "LG_SOTF_AUTH__BOOTSTRAP_ADMIN_PASSWORD": password(),
        "POSTGRES_SUPERUSER_PASSWORD": password(),
        "LGSOTF_OWNER_PASSWORD": password(),
        "LGSOTF_APP_PASSWORD": password(),
    }


def existing_keys(path: Path) -> List[str]:
    if not path.exists():
        return []
    keys = []
    for line in path.read_text(encoding="utf-8").splitlines():
        stripped = line.strip()
        if stripped and not stripped.startswith("#") and "=" in stripped:
            keys.append(stripped.split("=", 1)[0].strip())
    return keys


def render_env(values: Dict[str, str]) -> str:
    return "".join(f"{k}={v}\n" for k, v in values.items())


# Keys copied into the Kubernetes runtime Secret from the caller's environment
# when set; the first two are required by the chart.
K8S_RUNTIME_PASSTHROUGH = (
    "LG_SOTF_DATABASE__URL",
    "LG_SOTF_REDIS__URL",
    "LG_SOTF_LLM__API_KEY",
    "ANTHROPIC_API_KEY",
    "OPENAI_API_KEY",
    "GOOGLE_API_KEY",
    "LG_SOTF_RESPONSE__WEBHOOK_SECRET",
)
K8S_REQUIRED_EXTERNAL = ("LG_SOTF_DATABASE__URL", "LG_SOTF_REDIS__URL")
BOOTSTRAP_PREFIX = "LG_SOTF_AUTH__BOOTSTRAP_ADMIN_"


def _kubectl_secret(name: str, values: Dict[str, str]) -> str:
    for key, value in values.items():
        if "\n" in value or "\r" in value:
            raise ValueError(f"{key} contains a line break and cannot be written as an env-file line")
    body = "".join(f"{k}={v}\n" for k, v in values.items())
    return (
        f"kubectl create secret generic {shlex.quote(name)} --from-env-file=/dev/stdin <<'LG_SOTF_SECRET_EOF'\n"
        f"{body}LG_SOTF_SECRET_EOF\n"
    )


def render_k8s(
    values: Dict[str, str],
    name: str,
    environ: Mapping[str, str] | None = None,
    admin_email: str | None = None,
) -> str:
    env = os.environ if environ is None else environ
    runtime = {
        k: v for k, v in values.items() if k.startswith("LG_SOTF_") and not k.startswith(BOOTSTRAP_PREFIX)
    }
    runtime.update({k: env[k] for k in K8S_RUNTIME_PASSTHROUGH if env.get(k)})
    out = [
        "# Generated by scripts/generate_secrets.py. Pipe to `sh` so values never appear in",
        "# argv or shell history. Commands use the current kubectl context's namespace",
        "# (kubectl config set-context --current --namespace=<ns>).",
        "",
        f"# Runtime Secret ({name}): api, worker, scheduler, migrate.",
    ]
    missing = [k for k in K8S_REQUIRED_EXTERNAL if k not in runtime]
    if missing:
        out.append("# Still to add before installing (not set in this environment): " + ", ".join(missing))
    if not any(k in runtime for k in K8S_RUNTIME_PASSTHROUGH[2:6]):
        out.append(
            "# Also add the LLM provider key (ANTHROPIC_API_KEY, OPENAI_API_KEY, GOOGLE_API_KEY"
            " or LG_SOTF_LLM__API_KEY)."
        )
    text = "\n".join(out) + "\n" + _kubectl_secret(name, runtime)

    migration_url = env.get("LG_SOTF_DATABASE__MIGRATION_URL")
    if migration_url:
        text += f"\n# Owner Secret ({name}-owner): migrate job and scheduler only.\n"
        text += _kubectl_secret(f"{name}-owner", {"LG_SOTF_DATABASE__MIGRATION_URL": migration_url})
    else:
        text += (
            f"\n# Two-role installs: create {name}-owner with LG_SOTF_DATABASE__MIGRATION_URL "
            "(schema-owner DSN) and set secrets.ownerSecret.\n"
        )

    email = admin_email or env.get("LG_SOTF_AUTH__BOOTSTRAP_ADMIN_EMAIL")
    if email:
        text += f"\n# Bootstrap Secret ({name}-bootstrap): migrate job only; delete after the first install.\n"
        text += _kubectl_secret(
            f"{name}-bootstrap",
            {
                "LG_SOTF_AUTH__BOOTSTRAP_ADMIN_EMAIL": email,
                "LG_SOTF_AUTH__BOOTSTRAP_ADMIN_PASSWORD": values["LG_SOTF_AUTH__BOOTSTRAP_ADMIN_PASSWORD"],
            },
        )
    else:
        text += (
            f"\n# First admin: re-run with --admin-email to also print {name}-bootstrap "
            "(set secrets.bootstrapSecret).\n"
        )
    return text


def main(argv: List[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    parser.add_argument("--append", type=Path, help="Append keys that are missing from this env file.")
    parser.add_argument("--format", choices=["env", "k8s"], default="env")
    parser.add_argument("--secret-name", default="lg-sotf", help="Secret name for --format k8s.")
    parser.add_argument("--admin-email", help="Bootstrap admin email for --format k8s (<name>-bootstrap Secret).")
    args = parser.parse_args(argv)

    values = generate()
    if args.append is not None:
        present = set(existing_keys(args.append))
        missing = {k: v for k, v in values.items() if k not in present}
        if missing:
            # A new file is created owner-read/write only; an existing one keeps its mode.
            fd = os.open(args.append, os.O_WRONLY | os.O_APPEND | os.O_CREAT, 0o600)
            with os.fdopen(fd, "a", encoding="utf-8") as fh:
                fh.write("\n# Generated by scripts/generate_secrets.py\n")
                fh.write(render_env(missing))
        print(f"{len(missing)} secret(s) added to {args.append}; {len(values) - len(missing)} already present")
        return 0
    if args.format == "k8s":
        sys.stdout.write(render_k8s(values, args.secret_name, admin_email=args.admin_email))
    else:
        sys.stdout.write(render_env(values))
    return 0


if __name__ == "__main__":
    sys.exit(main())
